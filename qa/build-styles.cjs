// Build-time only. WordPress ships the result, without Node dependencies.
const fs = require('node:fs'), path = require('node:path'), {minify} = require('csso');
const assets = path.join(__dirname, '../grant-publishing-site/assets');
const sources = ['site.css','design.css','premium.css'];
const input = sources.map(file => fs.readFileSync(path.join(assets,file),'utf8')).join('\n');
// Preserve source order and compatibility overrides, including authored native layouts.
const result = '/* Grant Publishing Co. Generated by qa/build-styles.cjs. */\n' + minify(input,{restructure:false}).css + '\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path.join(assets,'site.bundle.min.css'),'utf8') !== result) throw Error('CSS bundle is stale. Run node qa/build-styles.cjs.');
} else fs.writeFileSync(path.join(assets,'site.bundle.min.css'),result);
console.log(`${sources.length} sheets, ${Buffer.byteLength(input)} → ${Buffer.byteLength(result)} bytes; one request.`);
